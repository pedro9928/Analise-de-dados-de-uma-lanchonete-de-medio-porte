DROP DATABASE IF EXISTS lanchonete_operacao;
CREATE DATABASE lanchonete_operacao CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE lanchonete_operacao;

CREATE TABLE cargos (
    id_cargo      INT PRIMARY KEY,
    nome          VARCHAR(50)   NOT NULL,
    salario_base  DECIMAL(10,2) NOT NULL
);

CREATE TABLE funcionarios (
    id_funcionario     INT PRIMARY KEY,
    nome               VARCHAR(80) NOT NULL,
    id_cargo           INT NOT NULL,
    id_gerente         INT NULL,                -- aponta para outro funcionário (self join)
    data_admissao      DATE NOT NULL,
    data_desligamento  DATE NULL,               -- NULL = ainda trabalha na casa
    CONSTRAINT fk_func_cargo   FOREIGN KEY (id_cargo)   REFERENCES cargos (id_cargo),
    CONSTRAINT fk_func_gerente FOREIGN KEY (id_gerente) REFERENCES funcionarios (id_funcionario)
);

CREATE TABLE escalas (
    id_escala       INT PRIMARY KEY,
    id_funcionario  INT NOT NULL,
    data_escala     DATE NOT NULL,
    turno           ENUM('almoco','jantar') NOT NULL,   -- almoco: 10h-16h | jantar: 16h-23h
    CONSTRAINT fk_escala_func FOREIGN KEY (id_funcionario) REFERENCES funcionarios (id_funcionario),
    INDEX idx_escala_data (data_escala)
);

CREATE TABLE fornecedores (
    id_fornecedor  INT PRIMARY KEY,
    nome           VARCHAR(80) NOT NULL,
    cidade         VARCHAR(60) NOT NULL
);

CREATE TABLE insumos (
    id_insumo      INT PRIMARY KEY,
    nome           VARCHAR(80) NOT NULL,
    unidade        VARCHAR(10) NOT NULL,
    id_fornecedor  INT NOT NULL,
    CONSTRAINT fk_insumo_forn FOREIGN KEY (id_fornecedor) REFERENCES fornecedores (id_fornecedor)
);

CREATE TABLE compras_insumos (
    id_compra    INT PRIMARY KEY,
    id_insumo    INT NOT NULL,
    data_compra  DATE NOT NULL,
    quantidade   DECIMAL(10,1) NOT NULL,
    valor_total  DECIMAL(10,2) NOT NULL,
    CONSTRAINT fk_compra_insumo FOREIGN KEY (id_insumo) REFERENCES insumos (id_insumo),
    INDEX idx_compra_data (data_compra)
);


